import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const entries=[
 ['confirm_delivery(uuid)','fix-confirm-delivery.sql',true],
 ['decide_dispute(uuid,text,text)','fix-dispute-validation.sql',true],
 ['open_dispute(uuid,text,text)','fix-open-dispute-validation.sql',true],
 ['mark_shipped(uuid,text,text)','fix-shipping-inputs.sql',true],
 ['ship_return(uuid,text)','fix-shipping-inputs.sql',true],
 ['save_address(text,text)','fix-address-access.sql',true],
 ['quote_order(uuid,text)','fix-quote-validation.sql',true],
 ['create_order(uuid,uuid)','fix-create-order-guard.sql',true],
 ['cancel_order(uuid)','guard-cancel-payment-details.sql',true],
 ['set_order_escrow_snapshot(uuid,uuid,text,text,text,jsonb)','add-escrow-creation-snapshot.sql',false],
 ['confirm_order_funding_snapshot(uuid,uuid,text,integer,integer,bigint,bigint,jsonb)','add-funding-snapshot.sql',false],
 ['claim_escrow_submission(uuid,text,text,text,bigint,text,uuid)','add-escrow-submission-claims.sql',false],
 ['reconcile_escrow_submission(uuid,uuid,text,jsonb,boolean,text)','add-escrow-reconciliation.sql',false],
];
const values=entries.map(([signature,file,authenticated])=>{
 const source=fs.readFileSync(path.join(root,'supabase/security',file),'utf8');
 const name=signature.split('(')[0];
 const pattern=new RegExp('CREATE (?:OR REPLACE )?FUNCTION public\\.'+name+'\\s*\\([\\s\\S]*?AS \\$function\\$([\\s\\S]*?)\\$function\\$','i');
 const match=source.match(pattern);
 if(!match)throw Error('Reviewed function body not found: '+name);
 // Fingerprint detects deployment differences, not semantic equivalence.
 // Ignore only CR line endings and outer ASCII whitespace, not SQL formatting.
 const body=match[1].replace(/\r/g,'').replace(/^[ \t\n]+|[ \t\n]+$/g,'');
 const digest=createHash('md5').update(body,'utf8').digest('hex');
 return ` ('public.${signature}','${digest}',${authenticated})`;
});
const sql=`-- Generated by scripts/build-security-verification.mjs from reviewed SQL.
-- Catalogs only. No business functions called, no application data read.
-- A body mismatch requires review; formatting changes also change the digest.
BEGIN TRANSACTION READ ONLY;
WITH expected(signature,digest,authenticated_expected) AS (VALUES
${values.join(',\n')}
), verified AS (
 SELECT e.signature,e.authenticated_expected,p.oid,p.prosecdef,p.proconfig,
  p.oid IS NOT NULL AS present,
  coalesce(md5(btrim(replace(p.prosrc,chr(13),''),E' \\t\\n'))=e.digest,false) AS body_matches,
  coalesce(p.proconfig @> ARRAY['search_path=pg_catalog, public, pg_temp'],false) AS search_path_matches,
  CASE WHEN p.oid IS NOT NULL THEN has_function_privilege('anon',p.oid,'EXECUTE') END AS anon,
  CASE WHEN p.oid IS NOT NULL THEN has_function_privilege('authenticated',p.oid,'EXECUTE') END AS authenticated,
  CASE WHEN p.oid IS NOT NULL THEN has_function_privilege('service_role',p.oid,'EXECUTE') END AS service_role,
  EXISTS(SELECT 1 FROM aclexplode(coalesce(p.proacl,acldefault('f',p.proowner))) a
   WHERE a.grantee=0 AND a.privilege_type='EXECUTE') AS public_execute
 FROM expected e LEFT JOIN pg_catalog.pg_proc p ON p.oid=pg_catalog.to_regprocedure(e.signature)
)
SELECT jsonb_build_object(
 'reviewed_functions',(SELECT jsonb_agg(jsonb_build_object(
  'function',signature,'present',present,'body_matches',body_matches,
  'search_path_matches',search_path_matches,'security_definer',prosecdef,
  'anon',anon,'authenticated',authenticated,'service_role',service_role,'public_execute',public_execute,
  'access_matches',coalesce(NOT anon AND authenticated=authenticated_expected AND service_role AND NOT public_execute,false)
 ) ORDER BY signature) FROM verified),
 'other_security_definer_functions',(SELECT coalesce(jsonb_agg(jsonb_build_object(
  'function',p.oid::regprocedure::text,'search_path_settings',ARRAY(
   SELECT setting FROM unnest(p.proconfig) AS setting WHERE setting LIKE 'search_path=%'),
  'anon',has_function_privilege('anon',p.oid,'EXECUTE'),
  'authenticated',has_function_privilege('authenticated',p.oid,'EXECUTE')
 ) ORDER BY p.oid::regprocedure::text),'[]'::jsonb)
 FROM pg_catalog.pg_proc p JOIN pg_catalog.pg_namespace n ON n.oid=p.pronamespace
 WHERE n.nspname='public' AND p.prosecdef AND p.prokind='f'
 AND NOT EXISTS(SELECT 1 FROM verified v WHERE v.oid=p.oid))
) AS security_verification;
ROLLBACK;
`;
fs.writeFileSync(path.join(root,'supabase/security/verify-reviewed-functions.sql'),sql);
console.log(`Generated read-only verification for ${entries.length} reviewed function bodies.`);
