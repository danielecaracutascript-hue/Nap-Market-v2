import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';

export async function runCreateOrderTests(db,root,connect){
 await db.query(`CREATE ROLE postgres NOSUPERUSER NOBYPASSRLS;
 CREATE ROLE anon;CREATE ROLE authenticated;CREATE ROLE service_role;
 GRANT USAGE,CREATE ON SCHEMA public TO postgres;
 GRANT USAGE ON SCHEMA public TO anon,authenticated,service_role;
 CREATE SCHEMA auth AUTHORIZATION postgres;GRANT USAGE ON SCHEMA auth TO anon,authenticated;
 SET ROLE postgres;
 CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS
 $$ SELECT nullif(current_setting('test.actor',true),'')::uuid $$;
 CREATE TABLE profiles(id uuid PRIMARY KEY);
 CREATE TABLE listings(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),seller_id uuid NOT NULL REFERENCES profiles,
 status text NOT NULL DEFAULT 'active',price_eur_cents integer NOT NULL DEFAULT 10000,
 ship_from_country char(2) NOT NULL DEFAULT 'IT',package_size text NOT NULL DEFAULT 'small');
 CREATE TABLE addresses(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),user_id uuid NOT NULL REFERENCES profiles,
 country char(2) NOT NULL,encrypted_payload bytea NOT NULL);
 CREATE TABLE orders(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),listing_id uuid NOT NULL REFERENCES listings,
 buyer_id uuid NOT NULL REFERENCES profiles,seller_id uuid NOT NULL REFERENCES profiles,
 status text NOT NULL DEFAULT 'CREATED',price_eur_cents integer NOT NULL,shipping_eur_cents integer NOT NULL,
 btc_eur_rate numeric(18,2) NOT NULL,price_sats bigint NOT NULL,buyer_commission_sats bigint NOT NULL,
 seller_commission_sats bigint NOT NULL,shipping_sats bigint NOT NULL,expires_at timestamptz NOT NULL,
 address_id uuid REFERENCES addresses,dest_country char(2) NOT NULL,package_size text NOT NULL,
 escrow_index integer GENERATED BY DEFAULT AS IDENTITY UNIQUE,CHECK(buyer_id<>seller_id));
 CREATE TABLE order_events(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),order_id uuid REFERENCES orders,
 actor_id uuid REFERENCES profiles,actor_role text,type text,data jsonb);
 CREATE TABLE fx_rates(btc_eur numeric,fetched_at timestamptz);
 CREATE TABLE shipping_rates(from_country char(2),to_country char(2),package_size text,price_eur_cents integer);
 INSERT INTO fx_rates VALUES(100000,now());INSERT INTO shipping_rates VALUES('IT','IT','small',1000);
 ALTER TABLE orders ENABLE ROW LEVEL SECURITY;ALTER TABLE listings ENABLE ROW LEVEL SECURITY;
 ALTER TABLE addresses ENABLE ROW LEVEL SECURITY;
 GRANT SELECT ON orders,listings,addresses TO authenticated;
 CREATE POLICY own_orders ON orders FOR SELECT USING(buyer_id=auth.uid() OR seller_id=auth.uid());
 CREATE POLICY readable_listing ON listings FOR SELECT USING(status='active' OR seller_id=auth.uid());
 CREATE POLICY own_addresses ON addresses FOR SELECT USING(user_id=auth.uid());`);
 const uid=n=>`00000000-0000-4000-8000-${String(n).padStart(12,'0')}`;
 const [seller,buyer,other,missingProfile]=[1,2,3,4].map(uid);
 await db.query('INSERT INTO profiles VALUES($1),($2),($3)',[seller,buyer,other]);
 const addresses={};for(const actor of [seller,buyer,other])addresses[actor]=(await db.query("INSERT INTO addresses(user_id,country,encrypted_payload) VALUES($1,'IT',convert_to('Synthetic address','UTF8')) RETURNING id",[actor])).rows[0].id;
 await db.query(fs.readFileSync(path.join(root,'supabase/security/fix-quote-validation.sql'),'utf8'));
 await db.query(fs.readFileSync(path.join(root,'tests/fixtures/audited-create-order.sql'),'utf8'));
 const listing=async(status='active')=>(await db.query('INSERT INTO listings(seller_id,status) VALUES($1,$2) RETURNING id',[seller,status])).rows[0].id;
 const call=async(actor,id,address=addresses[actor])=>{
  await db.query("SELECT set_config('test.actor',$1,true)",[actor]);await db.query('SET LOCAL ROLE authenticated');
  const result=await db.query('SELECT public.create_order($1,$2) AS id',[id,address]);
  await db.query('SET LOCAL ROLE postgres');return result.rows[0].id;
 };
 // Reproduce the audited function's old behavior on an already reopened listing.
 const old=await listing();await db.query('BEGIN');
 await call(buyer,old);await db.query("UPDATE listings SET status='active' WHERE id=$1",[old]);
 await call(other,old);assert.equal((await db.query('SELECT count(*)::int AS n FROM orders WHERE listing_id=$1',[old])).rows[0].n,2);
 await db.query('ROLLBACK');let count=1;
 const patch=fs.readFileSync(path.join(root,'supabase/security/fix-create-order-guard.sql'),'utf8');
 assert.deepEqual((await db.query(patch)).at(-1).rows[0],{function_name:'create_order',settings:['search_path=pg_catalog, public, pg_temp'],anon:false,authenticated:true,service_role:true});
 await db.query(patch);count+=2;
 const snapshot=async id=>(await db.query(`SELECT jsonb_build_object(
 'listing',(SELECT row_to_json(l) FROM listings l WHERE id=$1),
 'orders',(SELECT jsonb_agg(o ORDER BY o.id) FROM orders o WHERE listing_id=$1),
 'events',(SELECT jsonb_agg(e ORDER BY e.id) FROM order_events e JOIN orders o ON o.id=e.order_id WHERE o.listing_id=$1)) AS value`,[id])).rows[0].value;
 const test=async(name,fn)=>{await db.query('BEGIN');try{await fn();count++;console.log('PASS: '+name)}finally{await db.query('ROLLBACK')}};
 const rejected=async(id,fn,code='P0001')=>{
  const before=await snapshot(id);await db.query('SAVEPOINT invalid');await assert.rejects(fn,e=>e.code===code);
  await db.query('ROLLBACK TO SAVEPOINT invalid');assert.deepEqual(await snapshot(id),before);
 };
 for(const [actor,address] of [['',addresses[buyer]],[seller,addresses[seller]],[buyer,addresses[other]],[buyer,uid(999)],[missingProfile,addresses[buyer]]]){
  const id=await listing();await test('invalid actor/address cannot reserve listing',()=>rejected(id,()=>call(actor,id,address)));
 }
 for(const status of ['reserved','sold','removed']){
  const id=await listing(status);await test('unavailable listing unchanged',()=>rejected(id,()=>call(buyer,id)));
 }
 for(const status of ['CREATED','FUNDED','COMPLETED','CANCELLED','REFUNDED']){
  const id=await listing();await test('reopened listing guarded against existing order: '+status,async()=>{
   const first=await call(buyer,id);await db.query('UPDATE orders SET status=$1 WHERE id=$2',[status,first]);
   await db.query("UPDATE listings SET status='active' WHERE id=$1",[id]);
   if(['CANCELLED','REFUNDED'].includes(status)){await call(other,id);assert.equal((await snapshot(id)).orders.length,2)}
   else await rejected(id,()=>call(other,id));
  });
 }
 const valid=await listing();await test('complete create function stores coherent quote/reservation/event',async()=>{
  const orderId=await call(buyer,valid);const state=await snapshot(valid),o=state.orders[0];
  assert.equal(o.id,orderId);assert.equal(o.buyer_id,buyer);assert.equal(o.address_id,addresses[buyer]);
  assert.equal(o.price_sats,100000);assert.equal(o.buyer_commission_sats,4000);assert.equal(o.shipping_sats,10000);
  assert.equal(state.listing.status,'reserved');assert.equal(state.events.length,1);assert.equal(state.events[0].actor_id,buyer);
  assert.equal((await db.query("SELECT expires_at-now()=interval '48 hours' AS correct FROM orders WHERE id=$1",[orderId])).rows[0].correct,true);
  // Simulate caller losing the acknowledged ID after the database write.
  await rejected(valid,()=>call(buyer,valid));
  await db.query("SELECT set_config('test.actor',$1,true)",[buyer]);await db.query('SET LOCAL ROLE authenticated');
  assert.equal((await db.query('SELECT id FROM orders WHERE listing_id=$1',[valid])).rows[0].id,orderId);
  await db.query('SET LOCAL ROLE postgres');
 });
 const repriced=await listing();await test('FX recalculation at create remains internally consistent',async()=>{
  const before=(await db.query("SELECT quote_order($1,'IT') AS q",[repriced])).rows[0].q;
  await db.query('UPDATE fx_rates SET btc_eur=125000');await call(buyer,repriced);
  const state=await snapshot(repriced);assert.equal(before.price_sats,100000);assert.equal(state.orders[0].price_sats,80000);
  assert.equal(state.orders[0].btc_eur_rate,125000);assert.equal(state.events[0].data.price_sats,80000);
 });
 for(const mode of ['quote','event']){
  const id=await listing();await test('failure rolls back complete order/reservation/event: '+mode,async()=>{
   if(mode==='quote')await db.query('UPDATE fx_rates SET btc_eur=0');
   else await db.query(`CREATE FUNCTION fail_event() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'synthetic failure'; END $$;
    CREATE TRIGGER fail_event BEFORE INSERT ON order_events FOR EACH ROW EXECUTE FUNCTION fail_event()`);
   await rejected(id,()=>call(buyer,id));
  });
 }
 const anonymous=await listing();await test('anonymous RPC denied',async()=>{
  await db.query('SET LOCAL ROLE anon');await db.query('SAVEPOINT denied');
  await assert.rejects(()=>db.query('SELECT create_order($1,$2)',[anonymous,addresses[buyer]]),e=>e.code==='42501');
  await db.query('ROLLBACK TO SAVEPOINT denied');
 });
 // Two full create_order calls on separate PostgreSQL sessions.
 const raceId=await listing(),contender=await connect();
 const mainPid=(await db.query('SELECT pg_backend_pid() AS pid')).rows[0].pid;
 const otherPid=(await contender.query('SELECT pg_backend_pid() AS pid')).rows[0].pid;
 await db.query('BEGIN');const winner=await call(buyer,raceId);
 await contender.query('BEGIN');await contender.query("SELECT set_config('test.actor',$1,true)",[other]);
 await contender.query('SET LOCAL ROLE authenticated');
 const pending=contender.query('SELECT create_order($1,$2)',[raceId,addresses[other]]).then(value=>({value}),error=>({error}));
 let blocked=false;
 for(let attempt=0;attempt<100;attempt++){
  if((await db.query('SELECT pg_blocking_pids($1) AS p',[otherPid])).rows[0].p.includes(mainPid)){blocked=true;break}
  await new Promise(resolve=>setTimeout(resolve,20));
 }
 await db.query('COMMIT');const result=await pending;assert.equal(blocked,true);assert.equal(result.error?.code,'P0001');
 await contender.query('ROLLBACK');await contender.end();
 const raced=await snapshot(raceId);assert.equal(raced.orders.length,1);assert.equal(raced.orders[0].id,winner);assert.equal(raced.events.length,1);count++;
 // Caller discards the successful ID; another connection retries after COMMIT.
 const lostId=await listing();await db.query('BEGIN');await call(buyer,lostId);await db.query('COMMIT');
 const reconnected=await connect();await reconnected.query('BEGIN');
 await reconnected.query("SELECT set_config('test.actor',$1,true)",[buyer]);await reconnected.query('SET LOCAL ROLE authenticated');
 await assert.rejects(()=>reconnected.query('SELECT create_order($1,$2)',[lostId,addresses[buyer]]),error=>error.code==='P0001');
 await reconnected.query('ROLLBACK');await reconnected.query('SET ROLE authenticated');
 await reconnected.query("SELECT set_config('test.actor',$1,false)",[buyer]);
 const recovered=await reconnected.query('SELECT id FROM orders WHERE listing_id=$1',[lostId]);
 assert.equal(recovered.rowCount,1);assert.equal((await snapshot(lostId)).events.length,1);
 await reconnected.end();count++;
 console.log(`PASS: ${count} full create_order PostgreSQL checks, including old duplicate reproduction and two actual competing buyers. Schema/defaults synthetic; no Bitcoin or real data.`);
}
